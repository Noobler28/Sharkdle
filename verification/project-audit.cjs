const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const root = path.resolve(__dirname, '..');
const report = { scripts: 0, inlineScripts: 0, pages: 0, resources: 0, syntaxErrors: [], missing: [], caseMismatches: [] };
const ignored = new Set(['node_modules', '.git', '.codex', '.agents', '.codex-remote-attachments', 'dist', 'platforms']);
function files(directory) {
    return fs.readdirSync(directory, { withFileTypes: true }).flatMap(entry => {
        const file = path.join(directory, entry.name);
        return entry.isDirectory() ? (entry.name.startsWith('.') || ignored.has(entry.name) ? [] : files(file)) : [file];
    });
}
const relative = file => path.relative(root, file).replace(/\\/g, '/');
const directories = new Map();
function exactCase(file) {
    const segments = path.relative(root, file).split(path.sep);
    let directory = root;
    for (const segment of segments) {
        if (!directories.has(directory)) directories.set(directory, fs.readdirSync(directory));
        const names = directories.get(directory);
        if (!names.includes(segment)) return false;
        directory = path.join(directory, segment);
    }
    return true;
}
function checkResource(value, base, from) {
    if (!value || /^(?:data:|blob:|javascript:|mailto:|tel:|#)/i.test(value) || value.includes('${')) return;
    let url;
    try { url = new URL(value.replace(/&amp;/g, '&'), base); } catch { return; }
    if (url.origin !== 'https://local.test') return;
    let file;
    try { file = path.resolve(root, '.' + decodeURIComponent(url.pathname)); } catch { return; }
    if (path.basename(file) === 'cordova.js') return; // Generated by Cordova at build time.
    report.resources++;
    if (!fs.existsSync(file)) report.missing.push({ from, value, resolved: relative(file) });
    else if (!exactCase(file)) report.caseMismatches.push({ from, value, resolved: relative(file) });
}
for (const file of files(root)) {
    const extension = path.extname(file).toLowerCase();
    if (!['.js', '.cjs', '.html', '.css'].includes(extension)) continue;
    const source = fs.readFileSync(file, 'utf8'), name = relative(file);
    if (['.js', '.cjs'].includes(extension)) {
        report.scripts++;
        try { new vm.Script(source, { filename: name }); }
        catch (error) { report.syntaxErrors.push({ file: name, error: error.message }); }
    }
    if (extension === '.html') {
        report.pages++;
        for (const [index, match] of [...source.matchAll(/<script\b([^>]*)>([\s\S]*?)<\/script\s*>/gi)].entries()) {
            if (/\bsrc\s*=|\btype\s*=\s*["'](?:application\/|module)/i.test(match[1]) || !match[2].trim()) continue;
            report.inlineScripts++;
            try { new vm.Script(match[2], { filename: name + ':inline-' + index }); }
            catch (error) { report.syntaxErrors.push({ file: name + ':inline-' + index, error: error.message }); }
        }
        const page = new URL(name, 'https://local.test/');
        const baseTag = source.match(/<base\b[^>]*\bhref\s*=\s*["']([^"']+)["']/i);
        const base = baseTag ? new URL(baseTag[1], page) : page;
        const markup = source.replace(/<!--[^]*?-->/g, '').replace(/<script\b[^>]*>[^]*?<\/script>/gi, tag => tag.slice(0, tag.indexOf('>') + 1));
        for (const match of markup.matchAll(/<(script|link|img|source|video|audio|iframe)\b([^>]*)>/gi)) {
            for (const attribute of match[2].matchAll(/\b(src|href|poster)\s*=\s*["']([^"']*)["']/gi)) checkResource(attribute[2], base, name);
        }
    }
    if (extension === '.css') {
        for (const match of source.matchAll(/url\(\s*(?:"([^"]*)"|'([^']*)'|([^"')]*))\s*\)/gi)) checkResource((match[1] ?? match[2] ?? match[3]).trim(), new URL(name, 'https://local.test/'), name);
    }
}
fs.writeFileSync(path.join(__dirname, 'project-audit-results.json'), JSON.stringify(report, null, 2) + '\n');
console.log(JSON.stringify({ ...report, missing: report.missing.slice(0, 16), caseMismatches: report.caseMismatches.slice(0, 16), totalMissing: report.missing.length, totalCaseMismatches: report.caseMismatches.length }, null, 2));
if (report.syntaxErrors.length) process.exitCode = 1;
